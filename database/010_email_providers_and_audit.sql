create or replace function public.record_audit_event(
  p_action text,
  p_resource text,
  p_resource_id text default null,
  p_details jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_email text;
  v_actor_name text;
  v_id bigint;
begin
  if v_actor is null then raise exception 'Sessão ausente'; end if;
  if p_action not in ('SELECT','LOGIN','LOGOUT') then raise exception 'Ação não permitida'; end if;
  select email, name into v_actor_email, v_actor_name from public.users where id = v_actor;
  insert into public.audit_logs (action, resource, resource_id, actor_user_id, actor_email, actor_name, details)
  values (p_action, left(coalesce(p_resource, 'app'), 120), left(p_resource_id, 120), v_actor, v_actor_email, v_actor_name, coalesce(p_details, '{}'::jsonb))
  returning id into v_id;
  return v_id;
end;
$$;

revoke all on function public.record_audit_event(text, text, text, jsonb) from public, anon;
grant execute on function public.record_audit_event(text, text, text, jsonb) to authenticated;

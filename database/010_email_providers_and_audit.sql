-- Crescer+ / Supabase — provedores de e-mail e auditoria administrativa

create table if not exists public.email_providers (
  id uuid primary key default gen_random_uuid(),
  provider text not null check (provider in ('native', 'resend', 'mailtrap')),
  name text not null,
  enabled boolean not null default false,
  from_email text not null default '',
  from_name text not null default 'Crescer+',
  reply_to text not null default '',
  secret_env_name text not null default '',
  config_json jsonb not null default '{}'::jsonb,
  last_tested_at timestamptz null,
  last_test_status text null check (last_test_status in ('ok', 'failed', 'manual')),
  last_test_message text null,
  created_by uuid null references public.users(id) on delete set null,
  updated_by uuid null references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists uq_email_providers_provider on public.email_providers(provider);
create index if not exists idx_email_providers_enabled on public.email_providers(enabled);

create table if not exists public.email_deliveries (
  id uuid primary key default gen_random_uuid(),
  provider_id uuid null references public.email_providers(id) on delete set null,
  event_type text not null check (event_type in ('signup','invite','recovery','magiclink','email_change','notification','test')),
  recipient text not null,
  subject text not null default '',
  status text not null check (status in ('sent','failed','manual')),
  provider_message_id text null,
  error_message text null,
  created_by uuid null references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_email_deliveries_created_at on public.email_deliveries(created_at desc);
create index if not exists idx_email_deliveries_status on public.email_deliveries(status, created_at desc);
create index if not exists idx_email_deliveries_event_type on public.email_deliveries(event_type, created_at desc);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  action text not null check (action in ('SELECT','INSERT','UPDATE','DELETE','LOGIN','LOGOUT','SEND_EMAIL','SYSTEM')),
  resource text not null,
  resource_id text null,
  actor_user_id uuid null references public.users(id) on delete set null,
  actor_email text null,
  actor_name text null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_audit_logs_created_at on public.audit_logs(created_at desc);
create index if not exists idx_audit_logs_action on public.audit_logs(action, created_at desc);
create index if not exists idx_audit_logs_resource on public.audit_logs(resource, created_at desc);
create index if not exists idx_audit_logs_actor_email on public.audit_logs(actor_email, created_at desc);

alter table public.email_providers enable row level security;
alter table public.email_deliveries enable row level security;
alter table public.audit_logs enable row level security;

drop policy if exists "email_providers_super_admin" on public.email_providers;
drop policy if exists "email_deliveries_super_admin" on public.email_deliveries;
drop policy if exists "audit_logs_super_admin" on public.audit_logs;

